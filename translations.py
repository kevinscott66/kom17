def t(lang: str, key: str, **kwargs: Any) -> str:
    """
    Returns translation string for key. lang — 'ru' or 'en'.
    Supports placeholders: t('en', 'your_rank', rank='Moderator').
    For lang 'en' never falls back to Russian (no Russian in English locale).
    Never returns the raw key if a fallback translation exists (avoids showing keys like xxx_btn).
    """
    lang = "en" if (lang and str(lang).strip().lower() == "en") else "ru"
    fallback = _SUB_FALLBACKS_EN if lang == "en" else _SUB_FALLBACKS_RU
    d = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    s = d.get(key)
    if not s or (isinstance(s, str) and not s.strip()):
        s = fallback.get(key)
        if not s:
            if lang == "en":
                s = key
            else:
                s = TRANSLATIONS["en"].get(key) or TRANSLATIONS["ru"].get(key) or fallback.get(key) or key
    if not s:
        s = fallback.get(key) or key
    if kwargs:
        try:
            for pk, val in kwargs.items():
                s = s.replace("{" + pk + "}", str(val))
        except Exception:
            pass
    # Never show raw key to user: if result equals key, use fallback or placeholder.
    # For English locale never use Russian — only EN fallback or unknown_label.
    if s == key or (isinstance(s, str) and s.strip() == key):
        s = fallback.get(key)
        if not s and lang == "ru":
            s = TRANSLATIONS.get("en", {}).get(key)
        if not s or s == key:
            s = TRANSLATIONS.get(lang, {}).get("unknown_label") or TRANSLATIONS.get("en", {}).get("unknown_label") or "—"
    if s == key or (isinstance(s, str) and s.strip() == key):
        s = TRANSLATIONS.get(lang, {}).get("unknown_label") or TRANSLATIONS.get("en", {}).get("unknown_label") or "—"
    # Гарантия: пользователь никогда не видит сырой ключ
    if not s or s == key or (isinstance(s, str) and s.strip() == key):
        s = TRANSLATIONS.get(lang, {}).get("unknown_label") or TRANSLATIONS.get("en", {}).get("unknown_label") or "—"
    # Если результат похож на сырой ключ (содержит _ и только [a-z0-9_]) — не показывать
    if s and isinstance(s, str) and "_" in s and len(s) < 80 and _re.match(r"^[a-z0-9_]+$", s.strip()):
        s = TRANSLATIONS.get(lang, {}).get("unknown_label") or TRANSLATIONS.get("en", {}).get("unknown_label") or "—"
    # Для английской локали никогда не возвращаем строку с кириллицей
    if lang == "en" and s and isinstance(s, str) and _re.search(r"[а-яА-ЯёЁ]", s):
        s = _EN_KEY_TO_ENGLISH.get(key) or TRANSLATIONS.get("en", {}).get("unknown_label") or "—"
    return s
